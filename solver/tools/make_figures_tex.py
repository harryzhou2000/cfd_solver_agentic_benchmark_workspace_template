#!/usr/bin/env python3
"""Generate report/figures.tex: one labeled multi-panel figure per case from
report/figure_manifest.csv. Labels: fig:<shortlabel> (see CASE_LABELS)."""
import argparse
import csv
from pathlib import Path

CASE_LABELS = {
    "naca0012_m015_inviscid": "m015inv",
    "naca0012_m080_inviscid": "m080inv",
    "naca0012_m200_inviscid": "m200inv",
    "naca0012_m015_laminar_re5000": "m015lam",
    "naca0012_m080_laminar_re5000": "m080lam",
    "naca0012_m200_laminar_re5000": "m200lam",
    "cylinder_m010_laminar_re20": "re20",
    "cylinder_m010_laminar_re200": "re200",
}

# per case: ordered list of (variable-substring, subcaption)
PANELS = [
    ("residuals", "residual history", "residual history"),
    ("forces", "force history", "force history"),
    ("surface_cp", "surface $c_p$", "surface $c_p$"),
    ("surface_cf", "surface $c_f$", "surface $c_f$"),
    ("mach_zoom", "Mach (near body)", "mach"),
    ("pressure_zoom", "pressure (near body)", "pressure"),
    ("vorticity_wake", "wake vorticity (clipped)", "vorticity"),
    ("velocity_wake", "wake velocity magnitude", "velocity_magnitude"),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    entries = list(csv.DictReader(open(args.manifest)))
    by_case = {}
    for e in entries:
        by_case.setdefault(e["case_id"], []).append(e)

    lines = ["% auto-generated by tools/make_figures_tex.py"]
    for cid, short in CASE_LABELS.items():
        ents = by_case.get(cid)
        if not ents:
            continue
        lines.append("\\begin{figure}[htbp]\\centering")
        count = 0
        for key, subcap, _ in PANELS:
            match = [e for e in ents if e["figure_file"] == f"{cid}_{key.replace('_zoom','_zoom')}.png"]
            if key.endswith("_zoom"):
                match = [e for e in ents if e["figure_file"] == f"{cid}_{key}.png"]
            else:
                match = [e for e in ents if e["figure_file"] == f"{cid}_{key}.png"]
            if not match:
                continue
            e = match[0]
            lines.append("\\begin{subfigure}{0.48\\textwidth}\\centering")
            lines.append(f"\\includegraphics[width=\\textwidth]{{figures/{e['figure_file']}}}")
            lines.append(f"\\caption{{{subcap}}}")
            lines.append("\\end{subfigure}\\hfill")
            count += 1
            if count % 2 == 0:
                lines.append("")
        esc = cid.replace("_", "\\_")
        lines.append(f"\\caption{{Case \\texttt{{{esc}}}: residual and force histories, "
                     "surface distributions, and field contours. "
                     "Plotted variables are named in each subcaption.}")
        lines.append(f"\\label{{fig:{short}}}")
        lines.append("\\end{figure}")
        lines.append("")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
