#!/usr/bin/env python3
"""Generate LaTeX results tables + analysis JSON for the report.

Usage: .venv/bin/python tools/make_tables.py --results results --out report/tables.tex \
          --analysis report/analysis.json [--compare results_npX:label ...]
"""
import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np


def read_csv(path):
    with open(path) as fh:
        return list(csv.DictReader(fh))


def col(rows, name, dtype=float):
    return np.array([dtype(r[name]) for r in rows if r[name] not in (None, "")])


def analyze_case(cd: Path):
    meta = json.loads((cd / "metadata.json").read_text())
    status = json.loads((cd / "run_status.json").read_text())
    forces = read_csv(cd / "forces.csv")
    a = {
        "case_id": cd.name,
        "mpi_ranks": status["mpi_ranks"],
        "final_step": status["final_step"],
        "final_physical_time": status["final_physical_time"],
        "wall_time": status["wall_time_seconds"],
        "status": status["convergence_status"],
        "orders": status["residual_reduction_orders"],
    }
    transient = "re200" in cd.name
    if transient:
        cl = col(forces, "cl")
        cdv = col(forces, "cd")
        t = col(forces, "physical_time")
        n = len(cl) // 2  # post-transient half
        clp = cl[n:]
        cdp = cdv[n:]
        tp = t[n:]
        a["mean_cd"] = float(cdp.mean())
        a["cl_amplitude"] = float((clp.max() - clp.min()) / 2)
        a["cl_std"] = float(clp.std())
        # dominant frequency via FFT on cl (detrended)
        dt = float(np.mean(np.diff(tp)))
        sig = clp - clp.mean()
        win = np.hanning(len(sig))
        spec = np.abs(np.fft.rfft(sig * win))
        freqs = np.fft.rfftfreq(len(sig), dt)
        if len(spec) > 1:
            k = 1 + int(np.argmax(spec[1:]))
            a["dominant_freq"] = float(freqs[k])
            a["strouhal"] = float(freqs[k] * 1.0 / 1.0)  # D=1, U=1
            a["periods_observed"] = float(freqs[k] * (tp[-1] - tp[0]))
    else:
        a["cl"] = float(forces[-1]["cl"])
        a["cd"] = float(forces[-1]["cd"])
        a["cmz"] = float(forces[-1]["cmz"])
        a["pressure_drag"] = float(forces[-1]["pressure_drag"])
        a["viscous_drag"] = float(forces[-1]["viscous_drag"])
        # force stability over last 10%
        n = max(1, len(forces) // 10)
        cds = col(forces, "cd")[-n:]
        a["cd_std_last10"] = float(cds.std())
        # trailing-quarter time-mean (used for statistically periodic cases)
        m = max(1, len(forces) // 4)
        for key, out in [("cd", "cd"), ("cl", "cl"), ("cmz", "cmz"),
                         ("pressure_drag", "pdrag"), ("viscous_drag", "vdrag")]:
            v = col(forces, key)[-m:]
            a[f"{out}_mean"] = float(v.mean())
            a[f"{out}_std"] = float(v.std())
    inner = {k: meta.get(k) for k in [
        "typical_inner_iterations", "observed_min_inner_iterations",
        "observed_max_inner_iterations", "inner_target_misses",
        "inner_target_converged_fraction", "last_inner_residual_ratio"]}
    a["inner"] = inner
    return a


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--analysis", required=True)
    ap.add_argument("--compare", nargs="*", default=[])
    args = ap.parse_args()

    analyses = []
    for cd in sorted(Path(args.results).iterdir()):
        if not (cd / "metadata.json").exists():
            continue
        analyses.append(analyze_case(cd))
    Path(args.analysis).write_text(json.dumps(analyses, indent=2))

    lines = []
    lines.append("% auto-generated by tools/make_tables.py -- do not edit")
    # run-status table
    lines.append("\\begin{table}[htbp]\\centering\\small")
    lines.append("\\caption{Run status for all cases.}")
    lines.append("\\label{tab:runstatus}")
    lines.append("\\begin{tabular}{lrrrrrl}")
    lines.append("\\toprule")
    lines.append("case & ranks & steps & $t_\\mathrm{phys}$ & orders & wall [s] & status \\\\")
    lines.append("\\midrule")
    for a in analyses:
        lines.append(
            f"\\texttt{{{a['case_id'].replace('_', '\\_')}}}"
            f" & {a['mpi_ranks']} & {a['final_step']} & {a['final_physical_time']:.2f}"
            f" & {a['orders']:.2f} & {a['wall_time']:.0f} & {a['status'].replace('_', chr(92)+'_')} \\\\")
    lines.append("\\bottomrule\\end{tabular}\\end{table}")

    # force table
    lines.append("\\begin{table}[htbp]\\centering\\small")
    lines.append("\\caption{Force coefficients: final-row values for steady converged cases; "
                 "trailing-quarter time-mean $\\pm$ standard deviation for statistically "
                 "periodic cases (Mach 0.15 NACA, Re 200 cylinder).}")
    lines.append("\\label{tab:forces}")
    lines.append("\\begin{tabular}{lrrrrr}")
    lines.append("\\toprule")
    lines.append("case & $C_D$ & $C_L$ & $C_{m,z}$ & $C_{D,p}$ & $C_{D,v}$ \\\\")
    lines.append("\\midrule")
    for a in analyses:
        cid = a["case_id"].replace("_", "\\_")
        if "re200" in a["case_id"]:
            lines.append(
                f"\\texttt{{{cid}}} & {a['mean_cd']:.4f} & $\\pm${a['cl_amplitude']:.4f}"
                f" & -- & -- & -- \\\\")
        elif "m015" in a["case_id"] or a["status"] == "statistically_periodic":
            lines.append(
                f"\\texttt{{{cid}}} & {a['cd_mean']:.5f}$\\pm${a['cd_std']:.5f}"
                f" & {a['cl_mean']:.5f}$\\pm${a['cl_std']:.5f} & {a['cmz_mean']:.5f}"
                f" & {a['pdrag_mean']:.5f} & {a['vdrag_mean']:.5f} \\\\")
        else:
            lines.append(
                f"\\texttt{{{cid}}} & {a['cd']:.5f} & {a['cl']:.5f} & {a['cmz']:.5f}"
                f" & {a['pressure_drag']:.5f} & {a['viscous_drag']:.5f} \\\\")
    lines.append("\\bottomrule\\end{tabular}\\end{table}")

    # Re200 analysis table
    for a in analyses:
        if "re200" in a["case_id"]:
            lines.append("\\begin{table}[htbp]\\centering\\small")
            lines.append("\\caption{Vortex-street statistics for \\texttt{" +
                         a["case_id"].replace("_", "\\_") +
                         "} (post-transient half of the force history).}")
            lines.append("\\label{tab:re200stats}")
            lines.append("\\begin{tabular}{lr}\\toprule")
            lines.append(f"mean $C_D$ & {a['mean_cd']:.4f} \\\\")
            lines.append(f"$C_L$ amplitude & {a['cl_amplitude']:.4f} \\\\")
            lines.append(f"$C_L$ std & {a['cl_std']:.4f} \\\\")
            if "dominant_freq" in a:
                lines.append(f"dominant frequency $f$ & {a['dominant_freq']:.5f} \\\\")
                lines.append(f"Strouhal $St=fD/U$ & {a['strouhal']:.4f} \\\\")
                lines.append(f"shedding periods observed & {a['periods_observed']:.1f} \\\\")
            lines.append(f"inner iterations (mean/min/max) & {a['inner']['typical_inner_iterations']:.1f}"
                         f" / {a['inner']['observed_min_inner_iterations']}"
                         f" / {a['inner']['observed_max_inner_iterations']} \\\\")
            lines.append(f"inner target misses & {a['inner']['inner_target_misses']} \\\\")
            lines.append(f"inner converged fraction & {a['inner']['inner_target_converged_fraction']:.4f} \\\\")
            lines.append(f"last inner residual ratio & {a['inner']['last_inner_residual_ratio']:.2e} \\\\")
            lines.append("\\bottomrule\\end{tabular}\\end{table}")

    # parallel comparison table
    if args.compare:
        base = {a["case_id"]: a for a in analyses}
        lines.append("\\begin{table}[htbp]\\centering\\small")
        lines.append("\\caption{MPI rank-count comparison: converged force coefficients, "
                     "residual reduction, and wall time agree across rank counts "
                     "(wall times from a shared, oversubscribed machine).}")
        lines.append("\\label{tab:parallel}")
        lines.append("\\begin{tabular}{lrrrrr}\\toprule")
        lines.append("case & ranks & $C_D$ & $C_L$ & orders & wall [s] \\\\")
        lines.append("\\midrule")
        for spec in args.compare:
            cdir, label = spec.split(":", 1)
            for cd in sorted(Path(cdir).iterdir()):
                if not (cd / "run_status.json").exists():
                    continue
                ca = analyze_case(cd)
                ba = base.get(ca["case_id"])
                if ba is None:
                    continue
                for a in (ca, ba):
                    cid = a["case_id"].replace("_", "\\_")
                    lines.append(
                        f"\\texttt{{{cid}}} & {a['mpi_ranks']} & {a['cd']:.5f}"
                        f" & {a['cl']:.5f} & {a['orders']:.2f} & {a['wall_time']:.0f} \\\\")
                dcd = abs(ca["cd"] - ba["cd"])
                lines.append(f"\\multicolumn{{6}}{{l}}{{\\quad $\\Delta C_D$ = {dcd:.2e}}}\\\\")
        lines.append("\\bottomrule\\end{tabular}\\end{table}")

    # partition table (from first case with partition_diagnostics.csv)
    for cd in sorted(Path(args.results).iterdir()):
        pcsv = cd / "partition_diagnostics.csv"
        if not pcsv.exists():
            continue
        rows = read_csv(pcsv)
        owned = col(rows, "num_cells_owned", int)
        ghost = col(rows, "num_cells_ghost", int)
        neigh = col(rows, "num_neighbor_ranks", int)
        meta = json.loads((cd / "metadata.json").read_text())
        lines.append("\\begin{table}[htbp]\\centering\\small")
        lines.append("\\caption{Partition diagnostics for \\texttt{" +
                     cd.name.replace("_", "\\_") + "} (np=" + str(meta["mpi_ranks"]) +
                     "). Edge cut reported by METIS: " + str(meta.get("partition_edge_cut", "--")) + ".}")
        lines.append("\\label{tab:partition}")
        lines.append("\\begin{tabular}{rrrrr}\\toprule")
        lines.append("rank & owned & ghost & neighbors & send/recv \\\\")
        lines.append("\\midrule")
        send = col(rows, "send_cells", int)
        recv = col(rows, "recv_cells", int)
        for i, r in enumerate(rows):
            lines.append(f"{int(float(r['rank']))} & {int(float(r['num_cells_owned']))}"
                         f" & {int(float(r['num_cells_ghost']))} & {int(float(r['num_neighbor_ranks']))}"
                         f" & {int(float(r['send_cells']))}/{int(float(r['recv_cells']))} \\\\")
        lb = float(owned.max()) / max(1.0, float(owned.mean()))
        lines.append("\\midrule")
        lines.append(f"\\multicolumn{{5}}{{l}}{{load-balance ratio (max/mean owned): {lb:.3f};"
                     f" ghost fraction: {ghost.sum() / max(1, owned.sum()):.3f}}}\\\\")
        lines.append("\\bottomrule\\end{tabular}\\end{table}")
        break

    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out} and {args.analysis} ({len(analyses)} cases)")


if __name__ == "__main__":
    main()
