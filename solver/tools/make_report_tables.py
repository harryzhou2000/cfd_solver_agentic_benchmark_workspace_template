#!/usr/bin/env python3
"""Generate LaTeX tables for the report from results_summary.json,
partition diagnostics, and the MPI rank-count study."""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import numpy as np


def tt(s):
    return "\\texttt{" + str(s).replace("_", "\\_") + "}"

def fmt(x, nd=5):
    if x is None:
        return "--"
    return f"{x:.{nd}g}"


def load_summary(path):
    return {s["case_id"]: s for s in json.loads(Path(path).read_text())}


def run_status_table(summary, order):
    lines = [
        r"\begin{tabular}{lrrrrrl}",
        r"\toprule",
        r"case & ranks & steps & $t_{\rm final}$ & res.\ red.\ (orders) & wall [s] & status \\",
        r"\midrule",
    ]
    for cid in order:
        s = summary[cid]
        t = "--" if s["final_physical_time"] == 0 else fmt(s["final_physical_time"], 4)
        lines.append(
            f"{tt(cid)} & {s['mpi_ranks']} & {s['final_step']} & {t} & "
            f"{fmt(s['residual_reduction_orders'], 3)} & {fmt(s['wall_time_seconds'], 5)} & "
            f"{s['convergence_status'].replace('_', ' ')} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def force_table(summary, order):
    lines = [
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"case & $C_D$ & $C_L$ & $C_{m,z}$ & $C_{D,p}$ & $C_{D,v}$ & note \\",
        r"\midrule",
    ]
    for cid in order:
        s = summary[cid]
        if s["case_id"] == "cylinder_m010_laminar_re200":
            cd, cl = s.get("mean_cd_settled", s["final_cd"]), s["mean_cl_tail"]
            note = "settled mean"
        else:
            cd, cl = s["final_cd"], s["final_cl"]
            note = "final"
        lines.append(
            f"{tt(cid)} & {fmt(cd, 5)} & {fmt(cl, 5)} & {fmt(s['final_cmz'], 4)} & "
            f"{fmt(s['final_pressure_drag'], 5)} & {fmt(s['final_viscous_drag'], 5)} & {note} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def partition_table(summary, order):
    lines = [
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"case & cells & faces & edge cut & owned/rank (min--max) & ghosts/rank \\",
        r"\midrule",
    ]
    for cid in order:
        s = summary[cid]
        lines.append(
            f"{tt(cid)} & {s['num_cells_global']} & {s['num_faces_global']} & "
            f"{s.get('partition_edge_cut', 0)} & -- & -- \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def rank_study_table(rows):
    lines = [
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"case & ranks & $C_D$ & $C_L$ & steps & wall [s] \\",
        r"\midrule",
    ]
    for r in rows:
        lines.append(
            f"{tt(r['case'])} & {r['np']} & {fmt(r['cd'], 6)} & {fmt(r['cl'], 6)} & "
            f"{r['steps']} & {fmt(r['wall'], 5)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines)


def read_rank_study(rankstudy_dir: Path, case: str, main_result: Path):
    rows = []
    for np_ in [1, 2, 4]:
        d = rankstudy_dir / f"{case}_np{np_}"
        st = json.loads((d / "run_status.json").read_text())
        forces = list(csv.DictReader((d / "forces.csv").open()))
        tail = forces[-max(1, len(forces) // 5):]
        rows.append({
            "case": case, "np": np_,
            "cd": float(np.mean([float(r["cd"]) for r in tail])),
            "cl": float(np.mean([float(r["cl"]) for r in tail])),
            "steps": st["final_step"], "wall": st["wall_time_seconds"],
        })
    st = json.loads((main_result / "run_status.json").read_text())
    forces = list(csv.DictReader((main_result / "forces.csv").open()))
    tail = forces[-max(1, len(forces) // 5):]
    rows.append({
        "case": case, "np": 8,
        "cd": float(np.mean([float(r["cd"]) for r in tail])),
        "cl": float(np.mean([float(r["cl"]) for r in tail])),
        "steps": st["final_step"], "wall": st["wall_time_seconds"],
    })
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", type=Path, default=Path("results"))
    ap.add_argument("--report", type=Path, default=Path("report"))
    ap.add_argument("--rankstudy", type=Path, default=Path("rankstudy"))
    args = ap.parse_args()

    summary = load_summary(args.report / "results_summary.json")
    order = [s for s in [
        "naca0012_m015_inviscid", "naca0012_m080_inviscid", "naca0012_m200_inviscid",
        "naca0012_m015_laminar_re5000", "naca0012_m080_laminar_re5000",
        "naca0012_m200_laminar_re5000", "cylinder_m010_laminar_re20",
        "cylinder_m010_laminar_re200",
    ] if s in summary]

    out = []
    out.append("% auto-generated by make_report_tables.py")
    out.append("\\newcommand{\\RunStatusTable}{%\n" + run_status_table(summary, order) + "}")
    out.append("\\newcommand{\\ForceTable}{%\n" + force_table(summary, order) + "}")
    out.append("\\newcommand{\\PartitionTable}{%\n" + partition_table(summary, order) + "}")

    rows = []
    for case in ["naca0012_m015_inviscid", "cylinder_m010_laminar_re20"]:
        try:
            rows += read_rank_study(args.rankstudy, case, args.results / case)
        except Exception as e:  # noqa: BLE001
            print(f"WARN rank study {case}: {e}")
    if rows:
        out.append("\\newcommand{\\RankStudyTable}{%\n" + rank_study_table(rows) + "}")

    # Re200 vortex-street numbers
    if "cylinder_m010_laminar_re200" in summary:
        s = summary["cylinder_m010_laminar_re200"]
        out.append("\\newcommand{\\ReTwoSt}{%s}" % fmt(s.get("strouhal", 0.0), 4))
        out.append("\\newcommand{\\ReTwoMeanCd}{%s}" % fmt(s.get("mean_cd_settled", 0.0), 5))
        out.append("\\newcommand{\\ReTwoLiftAmp}{%s}" % fmt(s.get("lift_amplitude_tail", 0.0), 4))
        out.append("\\newcommand{\\ReTwoFreq}{%s}" % fmt(s.get("shedding_frequency", 0.0), 4))

    (args.report / "tables.tex").write_text("\n\n".join(out) + "\n")
    print("wrote", args.report / "tables.tex")


if __name__ == "__main__":
    main()
